def enrich_catalog(guides):
    """Apply the supplied detailed service data to existing catalog entries."""
    result = tuple(
        replace(guide, **UPDATES[guide.key])
        if guide.key in UPDATES
        else guide
        for guide in guides
    )

    assert len(result) == len(guides)
    assert len({guide.key for guide in result}) == len(result)

    return result
